"""Подробные реалистичные модели всего оружия (41 вид) для спрайтов в руках бойца и иконок.
Запуск:  blender -b --python dev/blender/make_weapons2.py -- [id ...]      (без имён — все)
Кадр в руках: 48×24 игровых единиц (x −16…32, y −12…12), рукоять в начале координат, ствол вдоль +x — как drawHeld.
Метательное (граната и т. п.) рисуется в том же кадре у руки и отдельно в своём кадре 16×16 (ent_<id>.png) для полёта.
WPN_OUT — папка (по умолчанию test-results/weapons2), WPN_PXU — пикселей на единицу (по умолчанию 16), WPN_SAMPLES."""
import bpy, math, os, sys, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wpn_lib as W
from wpn_lib import prof, box, cyl, ball, torus, screw, rail, grooves, tube_path, pbr, guard

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OUT = os.environ.get('WPN_OUT') or os.path.join(ROOT, 'test-results', 'weapons2')
PXU = int(os.environ.get('WPN_PXU', 16)); SAMPLES = int(os.environ.get('WPN_SAMPLES', 0)) or None


def held(name, build):
    sc = W.scene(-16, 32, -12, 12, PXU, SAMPLES); m = W.M(); W.M_DARK[0] = m.dark
    build(m)
    if os.environ.get('WPN_SAVE_BLEND') == '1':
        os.makedirs(OUT, exist_ok=True)
        bpy.ops.file.pack_all()   # HDRI внутри .blend: редактируемая сцена переносима
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(OUT, 'wpn_' + name + '.blend'))
    W.render(sc, os.path.join(OUT, 'wpn_' + name + '.png'))
    with open(os.path.join(OUT, 'wpn_' + name + '.json'), 'w', encoding='utf-8') as f:
        json.dump({'id': name, 'frame': [-16, 32, -12, 12], 'origin': [0, 0], 'pixels_per_unit': PXU,
                   'engine': sc.render.engine, 'samples': sc.cycles.samples, 'device': sc.cycles.device,
                   'material_source': 'procedural PBR', 'hdri': W.BLENDER_HDRI}, f, ensure_ascii=False, indent=2)


def thrown(name, build, hx=3.0):
    """метательное: в руке (центр предмета у руки, x≈3) и отдельно по центру своего кадра — для полёта"""
    sc = W.scene(-16, 32, -12, 12, PXU, SAMPLES); m = W.M(); W.M_DARK[0] = m.dark
    build(m, hx, 0.0); W.render(sc, os.path.join(OUT, 'wpn_' + name + '.png'))
    sc = W.scene(-8, 8, -8, 8, int(PXU * 1.5), SAMPLES); m = W.M(); W.M_DARK[0] = m.dark
    build(m, 0.0, 0.0); W.render(sc, os.path.join(OUT, 'ent_' + name + '.png'))


